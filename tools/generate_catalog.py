#!/usr/bin/env python3
"""Generate the C++ component catalogue from the reviewed schematic transcription."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'circuits/revisions.json').read_text())
scalar=['rin','sustainFoot','cIn','cCouple1','cCouple2','cCouple3','cOutput','toneInputCap','inputBypassCap','postInputLoad','outputShunt','cToneOutput']
arrays={'rc':4,'rf':4,'rb':4,'re':4,'rclip':2,'cFeedback':3,'cClip':2,'toneR':2,'toneC':2,'beta':4}
flags=['pnp','sustainLog','toneLog','volumeLog','toneReversed','volumeBeforeOutput','boost']
lines=['// Generated by tools/generate_catalog.py; edit circuits/revisions.json.','#pragma once','#include <array>','#include <cstddef>','namespace muff::circuit {','struct Revision {',' const char* id; const char* name;']
lines[5:5] = [f'inline constexpr double inputSourceResistance={data["inputSourceOhms"]};', f'inline constexpr double outputLoadResistance={data["outputLoadOhms"]};', f'inline constexpr double nominalSupply={data["supplyVolts"]};', f'inline constexpr double voltsPerFullScale={data["voltsPerFullScale"]};', f'inline constexpr double temperatureC={data["temperatureC"]};',f'inline constexpr double saturationCurrent={data["transistorModel"]["Is"]};',f'inline constexpr double reverseBeta={data["transistorModel"]["BetaReverse"]};',f'inline constexpr double forwardEarlyVoltage={data["transistorModel"]["Vaf"]};',f'inline constexpr double junctionBE={data["transistorModel"]["Cbe"]};',f'inline constexpr double junctionBC={data["transistorModel"]["Cbc"]};']
lines += [' double '+','.join(scalar)+';']
lines += [f' std::array<double,{n}> {k};' for k,n in arrays.items()]
lines += [' std::array<bool,2> clip;', ' bool '+','.join(flags)+';', ' double diodeIs,diodeN,diodeC;', '};',f'inline constexpr std::array<Revision,{len(data["models"])}> revisions {{{{']
for m in data['models']:
 diode=data['diodeModels'][m['diode']]
 v=[json.dumps(m['id']),json.dumps(m['name'])]+[repr(float(m[k])) for k in scalar]
 v+=['{{'+','.join(repr(float(x)) for x in m[k])+'}}' for k in arrays]
 v+=['{{'+','.join(str(x).lower() for x in m['clip'])+'}}']+[str(m[k]).lower() for k in flags]
 v+=[repr(diode[k]) for k in ('Is','N','C')]
 lines.append(' {'+','.join(v)+'},')
lines+=['}};','}']
text='\n'.join(lines)+'\n'
import sys
path=root/'Source/Circuit/Catalog.h'
if '--check' in sys.argv:
 if path.read_text()!=text:raise SystemExit('Generated circuit catalogue is stale')
else:path.write_text(text)
